function priceLines() {
  return PRICES.map((item) => {
    const parts = [];
    if (item.tonna) parts.push(`${item.tonna} ₽ за тонну`);
    if (item.meshok) parts.push(item.meshok);
    if (item.density) parts.push(`насыпная плотность ${item.density} т/м3`);
    return `- ${item.name}: ${parts.join('; ')}`;
  }).join('\n');
}

