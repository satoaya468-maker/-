export interface ChatMessage {
  role: 'user' | 'assistant';
  content: string;
}

/**
 * Резервный ответ, когда ключ API не задан.
 *
 * Это не «заглушка ради заглушки»: виджет должен продавать и без
 * подключённой модели, поэтому здесь живёт правиловый расчёт по тем же
 * формулам и тот же сбор телефона.
 */
export function stubReply(message: string, history: ChatMessage[]): string {
  const text = message.toLowerCase();

  // Префикс обязателен — та же строгость, что в /api/chat. С необязательным
  // префиксом за номер принимались любые десять цифр подряд, включая
  // габариты из сообщения о расчёте.
  const phone = message.match(/(?:\+?7|8)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}/);
  if (phone) {
    return 'Записал номер. Диспетчер перезвонит в течение 15 минут, зафиксирует цену и поставит машину в график. Если нужно срочно — наберите сами: +7 (3519) 55-04-04.';
  }

  // «12 на 6», «12х6», «12*6» — как прораб и пишет с телефона
  // Разделитель — группа с альтернативами, а не класс символов:
  // [хx*на] матчит ОДИН символ, поэтому «12 на 6» не распознавалось.
  const dims = message.match(/(\d+[.,]?\d*)\s*(?:на|[хx×*])\s*(\d+[.,]?\d*)/i);
  const thickness = message.match(/(\d+)\s*см/i);
  if (dims) {
    const l = Number(dims[1].replace(',', '.'));
    const w = Number(dims[2].replace(',', '.'));
    const t = thickness ? Number(thickness[1]) : 20;

    const isSand = /песок|песк/.test(text);
    const key = isSand ? 'sand-quarry' : 'gravel-20-40';
    const density = BULK_DENSITY[key].density;
    const product = PRODUCTS.find((p) => p.densityKey === key)!;

    const volume = l * w * (t / 100);
    const tons = volume * density * (isSand ? 1.15 : 1.2);
    const price = Math.round(
      (product.bulkFrom && tons >= product.bulkFrom.qty ? product.bulkFrom.price : product.basePrice) * tons,
    );

    return `${l}×${w} м при слое ${t} см — это ${volume.toFixed(1)} м³, по плотности ${density} т/м³ с запасом на уплотнение выходит ${tons.toFixed(1)} т ${isSand ? 'песка' : 'щебня'}. Материал — около ${price.toLocaleString('ru-RU')} ₽ без доставки. Оставьте номер — зафиксирую цену и поставлю машину в график.`;
  }

  if (/налич|есть ли|остат/.test(text)) {
    const top = PRODUCTS.slice(0, 3)
      .map((p) => `${p.title} — ${p.basePrice} ₽/${p.baseUnit}`)
      .join(', ');
    return `Сегодня на базе: ${top}. Всё с отгрузкой день в день. Скажите объём — посчитаю точную сумму, или оставьте номер, и диспетчер перезвонит за 15 минут.`;
  }

  if (/ндс|юрлиц|счёт|счет|безнал|организац/.test(text)) {
    return 'С юрлицами работаем по безналу с НДС, счёт выставляем в день заявки, закрывающие документы — УПД. Оставьте номер и ИНН, подготовим счёт.';
  }

  if (/доставк|привез|когда|срок/.test(text)) {
    return 'По Магнитогорску подаём машину от 30 минут, от 5 тонн доставка бесплатная. Пригород — 45 ₽/км, область считаем по адресу. Назовите адрес и объём — скажу точное время.';
  }

  if (/цен|стоим|сколько стоит|почём/.test(text)) {
    const p = PRODUCTS[0];
    return `Щебень ${p.spec} — ${p.basePrice} ₽/т, от 5 тонн ${p.bulkFrom?.price} ₽/т. Песок от 780 ₽/т, цемент М500 — 465 ₽ за мешок. Скажите объём, посчитаю итог с доставкой.`;
  }

  if (history.length === 0) {
    return GREETING;
  }

  return 'Чтобы посчитать точно, нужны размеры площадки и толщина слоя — например «12 на 6, слой 20 см». Или просто оставьте номер, и диспетчер всё посчитает за вас.';
}
