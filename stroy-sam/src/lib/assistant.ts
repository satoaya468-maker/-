/**
 * ИИ-менеджер «Семёныч».
 *
 * Задача у него ровно две: помочь прорабу посчитать материал и забрать
 * телефон. Всё остальное — вежливый отказ и перевод на диспетчера.
 */

import { BULK_DENSITY } from './units';
import { PRODUCTS } from './catalog';
import { WAREHOUSE, DELIVERY_ZONES, TRUCKS } from './warehouse';

export const ASSISTANT_NAME = 'Семёныч';

export const GREETING =
  'На связи Семёныч, менеджер базы на Западном шоссе. Скажите, что за объект и какой материал нужен — посчитаю объём и назову цену с доставкой.';

export const QUICK_REPLIES = [
  'Сколько щебня на стоянку 12×6?',
  'Цена песка с доставкой',
  'Что есть в наличии сегодня?',
  'Работаете с НДС?',
];

/**
 * Прайс и остатки уходят в системный промпт как факты: без них модель
 * начнёт выдумывать цены, а выдуманная цена в строймате — это скандал
 * на выгрузке.
 */
function catalogFacts(): string {
  return PRODUCTS.map((p) => {
    const bulk = p.bulkFrom
      ? `, от ${p.bulkFrom.qty} ${p.bulkFrom.unit} — ${p.bulkFrom.price} ₽`
      : '';
    return `- ${p.title} (${p.spec}), арт. ${p.sku}: ${p.basePrice} ₽/${p.baseUnit}${bulk}. Остаток ${p.stock}.`;
  }).join('\n');
}

function densityFacts(): string {
  return Object.values(BULK_DENSITY)
    .map((d) => `- ${d.label}: ${d.density} т/м³`)
    .join('\n');
}

